"""CWAVES : computation of CWAVE parameters from ocean wave / SAR spectra.

Public API
----------
- :func:`cwaves.compute_cwaves` : **the single entry point**. Computes the CWAVE
  parameters of a spectrum given as an ``xarray.DataArray`` on its native
  wavenumber grid -- cartesian (``k_rg``/``k_az``, uniform or not, e.g. FFT or
  sinh grids) or polar (``k``/``phi``), half plane (``k_rg >= 0``) or full
  plane. The grid is detected from the coordinates (see :mod:`cwaves.grid`);
  no resampling is performed.
- :func:`cwaves.compute_cwave_parameters` : historical ``xsar_slc`` signature,
  kept for API conservativeness; delegates to :func:`cwaves.compute_cwaves`.
- :func:`cwaves.reconstruct_spectrum` : reconstruction of a spectrum from its
  CWAVE parameters (maximum entropy, exact constraints, or linear).
- :func:`cwaves.compute_kernel` : the orthonormal CWAVE kernels.
- :func:`cwaves.gegenbauer_polynoms` / :func:`cwaves.harmonic_functions` :
  the radial and angular factors of the kernels.
- :func:`cwaves.symmetrize_xspectrum` : standalone utility rebuilding the full
  plane of a one-sided Hermitian cross-spectrum.
- :func:`cwaves.get_default_config` / :func:`cwaves.load_config` : the
  ``cwave_*`` configuration (the ``cwave`` block can be passed as kwargs).
- :func:`cwaves.compute_cwaves_from_file` : CLI-level helper (``cwaves
  --input-nc``) that detects the schema of a NetCDF file and calls
  :func:`cwaves.compute_cwaves` on its spectrum.

Reference
---------
J. Schulz-Stellenfleth, T. Konig, and S. Lehner, "An empirical approach for the
retrieval of integral ocean wave parameters from synthetic aperture radar data",
J. Geophys. Res., 112, C03019, 2007. doi:10.1029/2006JC003970
"""

